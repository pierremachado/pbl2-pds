% Regenera os dados dos gráficos. Não modifica as capturas originais.
% Execute da raiz: octave --no-gui --quiet docs/presentation/resultados/exportar_dados.m
here = fileparts(mfilename('fullpath'));
repo = fileparts(fileparts(fileparts(here)));
addpath(genpath(fullfile(repo, 'tools', 'octave', 'src')));
addpath(fullfile(repo, 'tools', 'octave', 'utils'));
data_dir = fullfile(repo, 'tools', 'octave', 'data');
m = analyzeSingleCapture(fullfile(data_dir, 'sample_20261106_102822_177.mat'), 2.56, 10, 'opt');
n = min(1800, numel(m.x_plot));
dlmwrite(fullfile(here, 'tempo_10hz.dat'), ...
    [m.x_plot(1:n), m.y_plot(1:n), m.ideal_cont_plot(1:n), ...
     m.err_vs_cont_lsb(1:n), m.err_intrinsic_lsb(1:n)], ...
    'delimiter', ' ', 'precision', '%.8g');
mask = m.freq_axis <= 180;
dlmwrite(fullfile(here, 'fft_10hz.dat'), ...
    [m.freq_axis(mask), m.mag_dbfs(mask), m.mag_dbfs_quant(mask), m.mag_dbfs_tri(mask)], ...
    'delimiter', ' ', 'precision', '%.8g');
dlmwrite(fullfile(here, 'linearidade_10hz.dat'), ...
    [m.codes_axis, m.dnl, m.inl, m.mean_adc_per_level], ...
    'delimiter', ' ', 'precision', '%.8g');
d = load(fullfile(data_dir, 'contraex_saturado_2v56_f05Hz_fs02000Hz.mat'));
dlmwrite(fullfile(here, 'contraex_saturado_2v56_f05Hz_fs02000Hz.dat'), ...
    [(0:numel(d.samples)-1)', d.samples(:)], 'delimiter', ' ', 'precision', '%.8g');
